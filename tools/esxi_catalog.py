"""Render the ESXi iPXE menu and image inventory from the reviewed catalog.

No packages are required. Use --check for an offline consistency check and
--verify-network to refresh HTTP Range/ISO9660 checks (never downloads full ISOs).
"""
import argparse
import concurrent.futures
import datetime
import json
import re
import sys
import urllib.error
import urllib.parse
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CATALOG = ROOT / 'catalog' / 'esxi.json'
HOSTS = {'downloads.dell.com', 'dl.dell.com', 'mirror.mahanserver.net',
         'pubdl.hausmer.com', 'pubdl-us1.hausmer.com'}
PAGE_SIZE = 12


def validate(catalog):
    seen = set()
    filenames = set()
    for image in catalog['images']:
        if not re.fullmatch(r'image_[a-f0-9]{12}', image['id']) or image['id'] in seen:
            raise ValueError('Duplicate or invalid image id')
        seen.add(image['id'])
        key = (image['vendor'], image['filename'].lower())
        if key in filenames:
            raise ValueError('Duplicate image filename within a vendor')
        filenames.add(key)
        url = urllib.parse.urlsplit(image['url'])
        if url.scheme not in ('https', 'http') or url.hostname not in HOSTS or url.username or url.password:
            raise ValueError('Unexpected download origin')
        if url.query or url.fragment or not url.path.lower().endswith('.iso'):
            raise ValueError('Only direct ISO paths are allowed')
        if urllib.parse.unquote(url.path.rsplit('/', 1)[-1]) != image['filename']:
            raise ValueError('URL and filename differ')
        if image['vendor'] == 'Dell' and url.hostname not in ('downloads.dell.com', 'dl.dell.com'):
            raise ValueError('Dell entries must download directly from Dell')
        for field in ('label', 'family', 'filename'):
            # Catalog values are embedded in an iPXE script. No executable syntax.
            if any(c in image[field] for c in '\r\n$;&|<>`'):
                raise ValueError(f'Unsafe characters in {field}')
        if image['vendor'] not in ('Dell', 'Standard', 'HPE'):
            raise ValueError('Unexpected vendor')
        if not re.fullmatch(r'\d+\.\d+', image['family']):
            raise ValueError('Invalid release family')
        if image.get('sha256') and not re.fullmatch('[a-f0-9]{64}', image['sha256']):
            raise ValueError('Invalid SHA256')
        if image.get('mirror_path') and image['url'] != 'https://mirror.mahanserver.net/VMware/ESXI/' + image['mirror_path']:
            raise ValueError('Mirror override path differs from the verified URL')
        for alternate in image.get('alternate_urls', []):
            candidate = urllib.parse.urlsplit(alternate)
            if candidate.scheme != 'https' or candidate.hostname not in HOSTS or candidate.query or candidate.fragment:
                raise ValueError('Unexpected alternate source')
            if urllib.parse.unquote(candidate.path.rsplit('/', 1)[-1]).lower() != image['filename'].lower():
                raise ValueError('Alternate source filename differs')


def sort_key(image):
    return (tuple(int(x) for x in re.findall(r'\d+', image['version'])),
            image['build'], int(re.sub(r'\D', '', image.get('revision', '')) or 0), image['filename'])


def ready(image):
    return image.get('check', {}).get('usable') is True


def render_menu(catalog):
    images = catalog['images']
    lines = ['#!ipxe', '# Generated by tools/esxi_catalog.py; edit catalog/esxi.json instead.',
             'isset ${esxi_mirror_base_url} || set esxi_mirror_base_url https://mirror.mahanserver.net/VMware/ESXI', '',
             ':esxi_menu', 'menu VMware ESXi - Select image',
             'item --gap Installer images by vendor']
    for vendor in ('Standard', 'Dell', 'HPE'):
        count = sum(i['vendor'] == vendor for i in images)
        source = {'Standard': 'VMware standard', 'Dell': 'Dell customized - official Dell URLs', 'HPE': 'HPE customized'}[vendor]
        lines.append(f'item vendor_{vendor.lower()} ${{space}} {source} ({count})')
    lines += ['item esxi_back ${space} Return to custom menu',
              'choose --default esxi_back esxi_choice || goto esxi_back', 'goto ${esxi_choice}', '']
    for vendor in ('Standard', 'Dell', 'HPE'):
        group = sorted((i for i in images if i['vendor'] == vendor), key=sort_key, reverse=True)
        families = sorted({i['family'] for i in group}, key=lambda v: tuple(map(int, v.split('.'))), reverse=True)
        parent = f'vendor_{vendor.lower()}'
        lines += [f':{parent}', f'menu ESXi - {vendor}', 'item --gap Choose release family']
        for family in families:
            label = f'{parent}_{family.replace(".", "_")}_1'
            count = sum(i['family'] == family for i in group)
            noun = 'image' if count == 1 else 'images'
            lines.append(f'item {label} ${{space}} ESXi {family} ({count} {noun})')
        lines += ['item esxi_menu ${space} Back', 'choose --default esxi_menu esxi_choice || goto esxi_menu',
                  'goto ${esxi_choice}', '']
        for family in families:
            entries = [i for i in group if i['family'] == family]
            pages = [entries[n:n + PAGE_SIZE] for n in range(0, len(entries), PAGE_SIZE)]
            stem = f'{parent}_{family.replace(".", "_")}'
            for page_number, page in enumerate(pages, 1):
                page_label = f'{stem}_{page_number}'
                lines += [f':{page_label}', f'menu ESXi {family} - {vendor} ({page_number}/{len(pages)})',
                          'item --gap [?] = download not confirmed; see inventory for details']
                for image in page:
                    indicator = '' if ready(image) else ' [?]'
                    lines.append(f'item {image["id"]} ${{space}} {image["label"]}{indicator}')
                if page_number > 1:
                    lines.append(f'item {stem}_{page_number - 1} ${{space}} Previous page')
                if page_number < len(pages):
                    lines.append(f'item {stem}_{page_number + 1} ${{space}} Next page')
                lines += [f'item {parent} ${{space}} Back to {vendor} versions',
                          f'choose --default {parent} esxi_choice || goto {parent}', 'goto ${esxi_choice}', '']
                for image in page:
                    url = image['url']
                    if image.get('mirror_path'):
                        url = '${esxi_mirror_base_url}/' + image['mirror_path']
                    lines += [f':{image["id"]}', f'set esxi_return {page_label}',
                              f'set esxi_url {url}', f'set esxi_image {image["filename"]}', 'clear esxi_alternate']
                    if image.get('alternate_urls'):
                        lines.append(f'set esxi_alternate {image["alternate_urls"][0]}')
                    lines += ['goto esxi_boot', '']
    lines += [':esxi_boot', 'imgfree', 'echo Starting ${esxi_image}',
              'sanboot --no-describe --drive 0x80 ${esxi_url} || goto esxi_failed', 'goto ${esxi_return}', '',
              ':esxi_failed', 'echo ISO boot failed. Check source access and iPXE HTTP(S) SAN support.',
              'echo The source may deny direct downloads. See the image inventory for details.',
              'echo For firmware ISO limitations, use extracted ESXi media over HTTP.',
              'menu ESXi - Download or boot failed',
              'isset ${esxi_alternate} && item esxi_try_alternate ${space} Try another published download source ||',
              'item esxi_retry ${space} Retry this source',
              'item esxi_return_to_list ${space} Return to image list',
              'choose --default esxi_return_to_list esxi_choice || goto esxi_return_to_list',
              'goto ${esxi_choice}', '', ':esxi_try_alternate', 'set esxi_url ${esxi_alternate}',
              'clear esxi_alternate', 'goto esxi_boot', '', ':esxi_retry', 'goto esxi_boot', '',
              ':esxi_return_to_list', 'goto ${esxi_return}', '',
              ':esxi_back', 'clear esxi_choice', 'clear esxi_image', 'clear esxi_url',
              'clear esxi_return', 'clear esxi_alternate', 'exit 0', '']
    return '\n'.join(lines)


def render_inventory(catalog):
    images = catalog['images']
    lines = ['# ESXi image inventory', '', f'Catalog reviewed: {catalog["reviewed_date"]}.', '',
             'Generated by `python tools/esxi_catalog.py`. Every row is a separate ISO filename; Dell Axx revisions are retained.', '',
             'A Range/ISO9660 check reads 64 bytes at offset 32768. It does not verify the full ISO hash or test booting.',
             'HTTP 403 can depend on CDN policy and client network. Such entries remain selectable as `[?]` because Dell publishes the actual ISO URL.',
             'A published SHA256 is reference metadata; iPXE sanboot does not verify it automatically.', '',
             'Dell coverage: [discovery audit](../catalog/dell-discovery.json). No guarantee is made that every historical or account-only release is public.', '']
    for vendor in ('Standard', 'Dell', 'HPE'):
        group = sorted((i for i in images if i['vendor'] == vendor), key=sort_key, reverse=True)
        lines += [f'## {vendor} ({len(group)})', '', '| Image | Build | Revision | Download check | ISO / source |',
                  '| --- | --- | --- | --- | --- |']
        for image in group:
            check = image.get('check', {})
            status = '206 + ISO9660' if ready(image) else str(check.get('status', 'not checked'))
            source = image['sources'][0]
            lines.append(f'| {image["version"]} {image.get("flavor", "")} | {image["build"]} | {image.get("revision", "")} | {status} | [{image["filename"]}]({image["url"]}) · [source]({source}) |')
            if image.get('sha256'):
                lines.append(f'| SHA256 | `{image["sha256"]}` | | | |')
        lines.append('')
    return '\n'.join(lines)


def probe(image):
    request = urllib.request.Request(image['url'], headers={'Range': 'bytes=32768-32831'})
    result = {'date': datetime.date.today().isoformat(), 'usable': False}
    try:
        with urllib.request.urlopen(request, timeout=20) as response:
            data = response.read(64)  # Never consume a full ISO if the server ignores Range.
            content_range = response.headers.get('Content-Range', '')
            result.update(status=response.status, range=content_range, iso9660=b'CD001' in data)
            result['usable'] = (response.status == 206 and len(data) == 64 and b'CD001' in data
                                and re.fullmatch(r'bytes 32768-32831/\d+', content_range) is not None)
            if result['usable']:
                result['size'] = int(content_range.split('/')[-1])
    except urllib.error.HTTPError as exc:
        result['status'] = exc.code
    except (OSError, ValueError) as exc:
        result.update(status='error', error=str(exc))
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='fail if generated files differ; no network')
    parser.add_argument('--verify-network', action='store_true', help='refresh checks before rendering; small Range requests only')
    args = parser.parse_args()
    if args.check and args.verify_network:
        parser.error('--check cannot modify the catalog')
    catalog = json.loads(CATALOG.read_text(encoding='utf-8'))
    validate(catalog)
    if args.verify_network:
        with concurrent.futures.ThreadPoolExecutor(max_workers=3) as pool:
            for image, check in zip(catalog['images'], pool.map(probe, catalog['images'])):
                image['check'] = check
        CATALOG.write_text(json.dumps(catalog, indent=2, ensure_ascii=False) + '\n', encoding='utf-8')
    outputs = {ROOT / 'esxi.ipxe': render_menu(catalog), ROOT / 'docs' / 'esxi-images.md': render_inventory(catalog)}
    for path, content in outputs.items():
        if args.check:
            if not path.exists() or path.read_text(encoding='utf-8') != content:
                raise ValueError(f'Generated file is stale: {path.name}')
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding='utf-8', newline='\n')
    print(f'{len(catalog["images"])} images; {sum(ready(i) for i in catalog["images"])} confirmed Range/ISO9660 checks')


if __name__ == '__main__':
    try:
        main()
    except (ValueError, KeyError) as exc:
        print(f'Error: {exc}', file=sys.stderr)
        sys.exit(1)
